def _rule(name, cond, constraint):
    return f'(rule "{name}"\n\t(condition "{cond}")\n\t(constraint {constraint}))\n'


def dru_limits(oz):
    """Custom rules for the limits pass (pass A). The board-wide minimums go in the .kicad_pro copy."""
    ring = LIMITS["pth_annular"][oz]
    r = ["(version 1)\n", "# JLCPCB capability limits, generated by tools/kicad/jlcpcb.py\n"]
    # For one constraint type the last matching rule wins outright, so each rule states min and max together.
    r.append(_rule("JLC hole size", "A.Type == 'Pad' || A.Type == 'Via'",
                   f"hole_size (min {LIMITS['via_drill']}mm) (max {LIMITS['pth_drill_max']}mm)"))
    r.append(_rule("JLC NPTH hole size", "A.Type == 'Pad' && A.Pad_Type == 'NPTH, mechanical'",
                   f"hole_size (min {LIMITS['npth_drill']}mm) (max {LIMITS['pth_drill_max']}mm)"))
    r.append(_rule("JLC PTH annular ring", "A.Type == 'Pad' && A.Pad_Type == 'Through-hole'",
                   f"annular_width (min {ring}mm)"))
    r.append(_rule("JLC pad hole to pad hole", "A.Type == 'Pad' && B.Type == 'Pad'",
                   f"hole_to_hole (min {LIMITS['pad_hole_to_hole']}mm)"))
    r.append(_rule("JLC PTH hole to copper", "A.Type == 'Pad' && A.Pad_Type == 'Through-hole'",
                   f"hole_clearance (min {LIMITS['pth_hole_clearance']}mm)"))
    r.append(_rule("JLC SMD pad to SMD pad",
                   "A.Type == 'Pad' && B.Type == 'Pad' && A.Pad_Type == 'SMD' && B.Pad_Type == 'SMD'",
                   f"clearance (min {LIMITS['smd_pad_to_pad']}mm)"))
    return "".join(r)


def dru_recommended(oz):
    """Rules for the recommended pass (pass B): the limits plus JLC's preferred values."""
    r = [dru_limits(oz).replace("capability limits", "recommended values")]
    r.append(_rule("JLC rec via hole", "A.Type == 'Via'",
                   f"hole_size (min {RECOMMENDED['via_drill']}mm) (max {LIMITS['pth_drill_max']}mm)"))
    r.append(_rule("JLC rec via ring", "A.Type == 'Via'", f"annular_width (min {RECOMMENDED['via_annular']}mm)"))
    r.append(_rule("JLC rec PTH ring", "A.Type == 'Pad' && A.Pad_Type == 'Through-hole'",
                   f"annular_width (min {max(RECOMMENDED['pth_annular'], LIMITS['pth_annular'][oz])}mm)"))
    r.append(_rule("JLC rec PTH hole to copper", "A.Type == 'Pad' && A.Pad_Type == 'Through-hole'",
                   f"hole_clearance (min {RECOMMENDED['pth_hole_clearance']}mm)"))
    r.append(_rule("JLC rec pad to track", "(A.Type == 'Pad' && B.Type == 'Track') || (A.Type == 'Track' && B.Type == 'Pad')",
                   f"clearance (min {RECOMMENDED['pad_to_track']}mm)"))
    return "".join(r)


def board_minimums(oz, recommended):
    """Values for board.design_settings.rules in the .kicad_pro copy."""
    m = {
        "min_clearance": LIMITS["clearance"][oz],
        "min_track_width": LIMITS["track_width"][oz],
        "min_via_diameter": LIMITS["via_diameter"],
        "min_via_annular_width": LIMITS["via_annular"],
        "min_through_hole_diameter": LIMITS["via_drill"],
        "min_hole_clearance": LIMITS["via_hole_clearance"],
        "min_hole_to_hole": LIMITS["via_hole_to_hole"],
        "min_copper_edge_clearance": LIMITS["copper_to_edge"],
        "min_silk_clearance": 0.0,
        "min_text_height": 0.0,
        "min_text_thickness": 0.0,
    }
    if recommended:
        m.update(min_silk_clearance=RECOMMENDED["silk_to_pad"], min_text_height=RECOMMENDED["silk_text_height"],
                 min_text_thickness=RECOMMENDED["silk_text_thickness"])
    return m


